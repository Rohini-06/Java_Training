public class methodreturn3 {
    static int add(int a, int b) {
        return a + b;
    }
    static int sub(int a, int b) {
        return a + b;
    }

    public static void main(String[] args) {
        System.out.println(add(10, 20));
        int r = sub(15, 5);
        System.out.println(r);
    }
}